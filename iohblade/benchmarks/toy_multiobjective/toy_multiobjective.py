"""Toy bi-objective benchmark for testing multi-objective support in BLADE.

The problem asks the LLM to generate a **search algorithm** that simultaneously
minimises two conflicting objectives on the bi-sphere function:

.. math::

    f_1(x) = x^2
    f_2(x) = (x - 2)^2

The Pareto front lies on :math:`x \\in [0, 2]`:

* Perfect minimiser of :math:`f_1` → :math:`x = 0`  (:math:`f_1=0, f_2=4`)
* Perfect minimiser of :math:`f_2` → :math:`x = 2`  (:math:`f_1=4, f_2=0`)

The algorithm generated by the LLM must implement::

    def run(self, objective, budget: int = 100) -> None:
        \"\"\"Search by calling ``objective(x) -> (f1, f2)`` at most
        ``budget`` times.\"\"\"

The harness owns the objective: it counts the evaluations, clips ``x`` to
``[-1, 3]`` and scores the best ``f1`` and best ``f2`` it actually observed,
so the value returned by ``run`` is ignored.

A reference solution is shown in :attr:`ToyMultiObjective.example_prompt`.
"""

from __future__ import annotations

import inspect
import math
import textwrap
from typing import Any

from iohblade.fitness import Fitness
from iohblade.problem import Problem
from iohblade.solution import Solution

_REFERENCE_CODE = textwrap.dedent("""\
    import numpy as np

    class BiSphereSearcher:
        \"\"\"Reference searcher for the toy bi-objective benchmark.

        Uniformly samples `budget` points in [-1, 3] and evaluates each
        of them with the objective provided by the harness.
        \"\"\"

        def run(self, objective, budget: int = 100):
            rng = np.random.default_rng(42)
            best_f1, best_f2 = float("inf"), float("inf")
            for x in rng.uniform(-1.0, 3.0, size=budget):
                f1, f2 = objective(x)
                best_f1, best_f2 = min(best_f1, f1), min(best_f2, f2)
            return best_f1, best_f2
    """)

LOWER, UPPER = -1.0, 3.0


class BudgetExhausted(Exception):
    """Raised by the harness objective once the evaluation budget is used."""


class _CountingObjective:
    """The bi-sphere objective as given to the candidate.

    Counts evaluations, refuses calls beyond the budget, clips ``x`` to the
    domain and records the best ``f1`` and ``f2`` that were evaluated.
    """

    def __init__(self, budget: int):
        self.budget = budget
        self.evaluations = 0
        self.over_budget_calls = 0
        self.best_f1 = math.inf
        self.best_f2 = math.inf
        self.best_x1 = math.nan
        self.best_x2 = math.nan

    def __call__(self, x) -> tuple[float, float]:
        if self.evaluations >= self.budget:
            self.over_budget_calls += 1
            raise BudgetExhausted(
                f"The budget of {self.budget} evaluations is exhausted."
            )
        x = float(x)
        if not math.isfinite(x):
            raise ValueError(f"x must be a finite number, got {x}.")
        x = min(max(x, LOWER), UPPER)
        self.evaluations += 1
        f1 = x**2
        f2 = (x - 2.0) ** 2
        if f1 < self.best_f1:
            self.best_f1, self.best_x1 = f1, x
        if f2 < self.best_f2:
            self.best_f2, self.best_x2 = f2, x
        return f1, f2


class ToyMultiObjective(Problem):
    """Toy bi-objective problem for demonstrating multi-objective support.

    The generated algorithm should search for a scalar :math:`x \\in [-1, 3]`
    that simultaneously minimises:

    * **f1** = :math:`x^2`           (distance to 0, in [0, 9])
    * **f2** = :math:`(x - 2)^2`     (distance to 2, in [0, 9])

    Both objectives conflict: a perfect solution for *f1* (*x* = 0) is the
    worst possible for *f2* and vice-versa.

    The returned :class:`~iohblade.fitness.Fitness` uses **negated** values so
    that larger is better, which is consistent with BLADE's maximisation
    convention:

    * ``fitness["f1"]`` = −best_f1  (maximise → minimise *f1*)
    * ``fitness["f2"]`` = −best_f2  (maximise → minimise *f2*)

    Parameters
    ----------
    budget:
        Number of function evaluations the generated algorithm may use.
    name:
        Problem name (shown in logs and plots).
    """

    task_prompt = textwrap.dedent("""\
        You are given a bi-objective optimisation task. Your goal is to write
        a Python class that searches for a scalar value x in [-1, 3] and
        simultaneously minimises:

            f1(x) = x ** 2
            f2(x) = (x - 2) ** 2

        These objectives conflict: the optimal x for f1 is 0, while the
        optimal x for f2 is 2. You should try to find a good compromise.

        Your class must be named `BiSphereSearcher` and implement the
        following interface:

            def run(self, objective, budget: int = 100):
                ...

        `objective(x)` evaluates one point and returns the tuple `(f1, f2)`.
        It may be called at most `budget` times; further calls raise an
        exception. Values of x outside [-1, 3] are clipped to that interval,
        and x must be a finite number. Your score is the best (lowest) f1
        and the best (lowest) f2 among the points you evaluated with
        `objective`; the value returned by `run` is ignored. You are free to
        use any search strategy you like (random search, grid search,
        gradient-free optimisation, etc.).
        """)

    # Built by concatenation (not a dedented f-string) so the code block is
    # not indented and its fences start at column 0.
    example_prompt = (
        "Here is a simple reference implementation:\n\n"
        "```python\n" + _REFERENCE_CODE.rstrip("\n") + "\n```\n"
    )

    format_prompt = textwrap.dedent("""\
        Your solution must be a Python class named `BiSphereSearcher` with a
        `run(self, objective, budget: int = 100)` method.
        Wrap the class in a Python code block:

        ```python
        class BiSphereSearcher:
            ...
        ```
        """)

    def __init__(self, budget: int = 100, name: str = "ToyMultiObjective"):
        super().__init__(name=name)
        # Problem.__init__ sets placeholder prompts on the instance, which
        # would shadow the class-level prompts defined above.
        self.task_prompt = ToyMultiObjective.task_prompt
        self.example_prompt = ToyMultiObjective.example_prompt
        self.format_prompt = ToyMultiObjective.format_prompt
        self.eval_budget = budget

    def get_prompt(self) -> str:  # pragma: no cover
        return (
            ToyMultiObjective.task_prompt
            + "\n\n"
            + ToyMultiObjective.example_prompt
            + "\n\n"
            + ToyMultiObjective.format_prompt
        )

    def evaluate(self, solution: Solution) -> Solution:
        """Execute the generated algorithm and score it with a Fitness object.

        Parameters
        ----------
        solution:
            A :class:`~iohblade.solution.Solution` whose ``code`` attribute
            must define a class ``BiSphereSearcher`` with a
            ``run(objective, budget)`` method.

        Returns
        -------
        Solution
            The same solution with ``fitness`` set to a
            :class:`~iohblade.fitness.Fitness` mapping
            ``{"f1": -best_f1, "f2": -best_f2}``, where ``best_f1`` and
            ``best_f2`` are the lowest values the harness observed. A failed
            solution gets ``-inf`` on both objectives.
        """
        namespace: dict = {}
        try:
            exec(solution.code, namespace)  # noqa: S102
        except Exception as exc:
            return solution.set_scores(
                fitness=self._failure(),
                feedback="Code failed to execute.",
                error=exc,
            )

        cls = namespace.get("BiSphereSearcher")
        if cls is None:
            return solution.set_scores(
                fitness=self._failure(),
                feedback="Class `BiSphereSearcher` not found in the generated code.",
                error="Class `BiSphereSearcher` not found in the generated code.",
            )

        objective = _CountingObjective(self.eval_budget)
        note = ""
        try:
            searcher = cls()
            searcher.run(objective, budget=self.eval_budget)
        except BudgetExhausted:
            note = (
                f" run() tried to use more than {self.eval_budget} "
                "evaluations; only the first ones were scored."
            )
        except Exception as exc:
            solution.set_scores(
                fitness=self._failure(),
                feedback=f"run() raised an exception: {exc}",
                error=exc,
            )
            return solution
        if objective.over_budget_calls and not note:
            note = (
                f" run() called the objective {objective.over_budget_calls} "
                f"time(s) after the budget of {self.eval_budget} was used; "
                "those calls were not scored."
            )

        if objective.evaluations == 0:
            msg = "run() never called the objective, so nothing was evaluated."
            return solution.set_scores(fitness=self._failure(), feedback=msg, error=msg)

        best_f1, best_f2 = objective.best_f1, objective.best_f2
        # BLADE maximises: negate so that closer to 0 → higher fitness
        fitness = Fitness({"f1": -best_f1, "f2": -best_f2})
        feedback = (
            f"Best f1 (x²) = {best_f1:.4f} at x = {objective.best_x1:.4f}, "
            f"best f2 ((x-2)²) = {best_f2:.4f} at x = {objective.best_x2:.4f}, "
            f"using {objective.evaluations}/{self.eval_budget} evaluations." + note
        )
        return solution.set_scores(fitness=fitness, feedback=feedback)

    def _failure(self) -> Fitness:
        """Worst fitness on both objectives, for an invalid solution."""
        worst = self.failure_fitness()
        return Fitness({"f1": worst, "f2": worst})

    def test(self, solution: Solution) -> Solution:
        """Run evaluate as the test phase (same logic as training)."""
        return self.evaluate(solution)

    def to_dict(self) -> dict:
        return {"name": self.name, "eval_budget": self.eval_budget}

    def get_config(self) -> dict[str, Any]:
        from iohblade.tags import (
            NoiseType,
            ObjectiveType,
            PrimaryCategories,
            VariableType,
        )

        tags: list[Any] = [
            "toy",
            PrimaryCategories.BBO,
            NoiseType.NOISELESS,
            ObjectiveType.MULTI_OBJECTIVE,
            VariableType.CONTINUOUS,
        ]

        evaluator = inspect.getsource(_CountingObjective) + inspect.getsource(
            self.evaluate
        )

        config = {
            "tags": tags,
            "name": "Toy Multi-Objective",
            "prompt": self.get_prompt(),
            "minimisation": False,
            "evaluator": evaluator,
            "config": {
                "budget": self.eval_budget,
                "keys": ["f1", "f2"],
                "depencencies": self.dependencies,
                "imports": self.imports,
            },
        }
        return config


if __name__ == "__main__":
    tm = ToyMultiObjective()
    for key, value in tm.get_config().items():
        print(f"------------------------------{key}------------------------------")
        print(value)
