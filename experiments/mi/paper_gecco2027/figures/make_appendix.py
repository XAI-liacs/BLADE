def _arm_rows(path, metrics, arms=None):
    """Rows 'arm & mean (diff [ci]) ...' from a paired.txt."""
    means, diffs, conc = parse_paired(path)
    arms = arms or [a for a in ARM_ORDER if a in means.index]
    rows = []
    for a in arms:
        cells = [ARM_TEX[a]]
        for m, nd in metrics:
            mv = means.loc[a, m]
            if a == "control" or a not in diffs or m not in diffs[a]:
                cells.append(f(mv, nd))
            else:
                n, d, lo, hi = diffs[a][m]
                s = f(d, nd, True)
                if lo > 0 or hi < 0:
                    s = r"\textbf{" + s + "}"
                cells.append(f"{f(mv, nd)} ({s})")
        rows.append(" & ".join(cells))
    return rows, means, diffs, conc


