# ---------------------------------------------------------------- helpers
def f(x, nd=2, sign=False):
    """Format a number for LaTeX (minus sign as math)."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$")


def ci(d, lo, hi, nd=2, bold=True):
    """Difference with CI; bold if the CI excludes 0."""
    s = f"{f(d, nd, True)} [{f(lo, nd, True)}, {f(hi, nd, True)}]"
    if bold and (lo > 0 or hi < 0):
        s = r"\textbf{" + f(d, nd, True) + "}" + s[len(f(d, nd, True)) :]
    return s


def write(name, body):
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / f"{name}.tex").write_text(
        "%% generated by figures/make_appendix.py; do not edit\n" + body
    )


def table(caption, label, colspec, header, rows, star=True, note=None, size="small"):
    env = "table*" if star else "table"
    out = [
        rf"\begin{{{env}}}[t]",
        rf"  \caption{{{caption}}}",
        rf"  \label{{{label}}}",
        rf"  \{size}",
        r"  \setlength{\tabcolsep}{3.5pt}",
        rf"  \begin{{tabular}}{{{colspec}}}",
        r"    \toprule",
        "    " + header + r"\\",
        r"    \midrule",
    ]
    for r in rows:
        out.append("    " + r if r.startswith("\\") else "    " + r + r"\\")
    out += [r"    \bottomrule", r"  \end{tabular}"]
    if note:
        out.append(r"  \\[2pt]\raggedright\footnotesize " + note)
    out.append(rf"\end{{{env}}}")
    return "\n".join(out) + "\n"


def parse_paired(path):
    """Parse a paired.txt written by exp05's 06 analysis script.

    Returns (means: DataFrame arm x metric, diffs: dict arm -> {metric:
    (n, d, lo, hi)}, concepts: DataFrame arm x concept).
    """
    lines = Path(path).read_text().splitlines()
    i = lines.index("per-arm mean over seeds")
    header = lines[i + 1].split()
    means = {}
    j = i + 3
    while not lines[j].startswith("paired diff"):
        parts = lines[j].split()
        means[parts[0]] = [float(v) for v in parts[1:]]
        j += 1
    means = pd.DataFrame(means, index=header).T
    diffs = {}
    j += 1
    pat = re.compile(r"(\w+)=([+-][\d.]+|nan) \[([+-][\d.]+|nan),([+-][\d.]+|nan)\]")
    while re.match(r"^\w+ \(n=\d+\)", lines[j]):
        arm, n = re.match(r"^(\w+) \(n=(\d+)\)", lines[j]).groups()
        diffs[arm] = {
            m: (int(n), float(a), float(b), float(c))
            for m, a, b, c in pat.findall(lines[j])
        }
        j += 1
    while "{" in lines[j]:
        j += 1
    cheader = lines[j].split()
    conc = {}
    j += 2
    while j < len(lines) and not lines[j].startswith("operator"):
        parts = lines[j].split()
        if len(parts) == len(cheader) + 1:
            conc[parts[0]] = [float(v) for v in parts[1:]]
        j += 1
    conc = pd.DataFrame(conc, index=cheader).T
    return means, diffs, conc


