def concept_table(conc, problem, label):
    cols = [
        ("population", "pop."),
        ("differential_evolution", "DE"),
        ("crossover", "cross."),
        ("elitism", "elit."),
        ("gradient", "grad."),
        ("step_size_adaptation", "step"),
        ("covariance", "cov."),
        ("local_search", "LS"),
        ("simulated_annealing", "SA"),
        ("particle_swarm", "PSO"),
    ]
    cols = [(c, n) for c, n in cols if c in conc.columns]
    rows = []
    for a in ARM_ORDER:
        if a not in conc.index:
            continue
        rows.append(
            " & ".join([ARM_TEX[a]] + [f"{100 * conc.loc[a, c]:.0f}" for c, _ in cols])
        )
    return table(
        rf"Concepts in the generated algorithms on {problem}: percentage"
        rf" of the algorithms of an arm that contain the concept (pop.:"
        rf" population, DE: differential evolution, cross.: crossover,"
        rf" elit.: elitism, grad.: gradient, step: step-size adaptation,"
        rf" cov.: covariance, LS: local search, SA: simulated annealing,"
        rf" PSO: particle swarm).",
        label,
        "l" + "r" * len(cols),
        "Arm & " + " & ".join(n for _, n in cols),
        rows,
        star=True,
    )


