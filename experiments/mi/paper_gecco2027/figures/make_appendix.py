def tab_counterfactual():
    e = pd.read_csv(E2 / "cf/cf_effects.csv")
    m = pd.read_csv(E2 / "cf/cf_means.csv")
    names = {
        ("error", "no_error"): "crashed parent: error trace deleted",
        ("error", "error_generic"): "crashed parent: generic error message",
        ("scored", "no_feedback"): "scored parent: feedback deleted",
        ("scored", "score_low"): "scored parent: score set to 0.01",
        ("scored", "score_high"): "scored parent: score set to 0.90",
        ("scored", "budget_msg"): "scored parent: budget message added",
        ("scored", "steer_up"): "scored parent: steer fitness up",
        ("scored", "steer_down"): "scored parent: steer fitness down",
        ("scored", "steer_random"): "scored parent: random direction",
    }
    rows = []
    for (st, v), lab in names.items():
        fe = e[(e.stratum == st) & (e.variant == v) & (e.metric == "failed")].iloc[0]
        sc = e[(e.stratum == st) & (e.variant == v) & (e.metric == "score")].iloc[0]
